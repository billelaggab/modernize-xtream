#!/usr/bin/env python3
"""Safe, non-interactive Ubuntu 24.04 / 26.04 installer for Madar.

The application runs in containers, so neither system Python nor Ubuntu's
libraries are replaced. Docker repository setup is opt-in via --install-docker.
"""

from __future__ import annotations

import argparse
import os
import platform
import secrets
import shutil
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENV_FILE = ROOT / "deploy" / ".env"
SUPPORTED = {"24.04", "26.04"}
DOCKER_DOCS = "https://docs.docker.com/engine/install/ubuntu/"


def os_release() -> dict[str, str]:
    path = Path("/etc/os-release")
    if not path.exists():
        return {}
    result: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if "=" in line and not line.startswith("#"):
            key, value = line.split("=", 1)
            result[key] = value.strip().strip('"')
    return result


def check_host(skip_os_check: bool = False) -> None:
    release = os_release()
    if not skip_os_check and (release.get("ID") != "ubuntu" or release.get("VERSION_ID") not in SUPPORTED):
        raise RuntimeError("Requires Ubuntu 24.04 or 26.04. Use --skip-os-check only for development.")
    if sys.version_info < (3, 12):
        raise RuntimeError("Python 3.12 or newer is required on the host.")
    print(f"[OK] {release.get('PRETTY_NAME', platform.platform())} | Python {platform.python_version()}")


def docker_available() -> bool:
    if not shutil.which("docker"):
        return False
    return subprocess.run(["docker", "compose", "version"], capture_output=True, check=False).returncode == 0


def run(command: list[str]) -> None:
    print("$", " ".join(command), flush=True)
    subprocess.run(command, cwd=ROOT, check=True)


def install_docker() -> None:
    """Install packages from Docker's official signed Ubuntu APT repository."""
    if os.geteuid() != 0:
        raise RuntimeError("Run with sudo to install Docker system packages.")
    release = os_release()
    codename = release.get("UBUNTU_CODENAME") or release.get("VERSION_CODENAME")
    if not codename or release.get("ID") != "ubuntu":
        raise RuntimeError("Cannot determine Ubuntu codename; see " + DOCKER_DOCS)
    run(["apt-get", "update"])
    run(["apt-get", "install", "-y", "ca-certificates"])
    keyring = Path("/etc/apt/keyrings")
    keyring.mkdir(parents=True, exist_ok=True, mode=0o755)
    key_path = keyring / "docker.asc"
    if not key_path.exists():
        with urllib.request.urlopen("https://download.docker.com/linux/ubuntu/gpg", timeout=30) as response:
            key = response.read(100_000)
        if not key.startswith(b"-----BEGIN PGP PUBLIC KEY BLOCK-----"):
            raise RuntimeError("Unexpected Docker signing key format. Aborting.")
        key_path.write_bytes(key)
        key_path.chmod(0o644)
    architecture = subprocess.check_output(["dpkg", "--print-architecture"], text=True).strip()
    sources = Path("/etc/apt/sources.list.d/docker.sources")
    if not sources.exists():
        sources.write_text(
            "Types: deb\nURIs: https://download.docker.com/linux/ubuntu\n"
            f"Suites: {codename}\nComponents: stable\nArchitectures: {architecture}\n"
            "Signed-By: /etc/apt/keyrings/docker.asc\n",
            encoding="utf-8",
        )
    run(["apt-get", "update"])
    run(["apt-get", "install", "-y", "docker-ce", "docker-ce-cli", "containerd.io", "docker-buildx-plugin", "docker-compose-plugin"])
    run(["systemctl", "enable", "--now", "docker"])


def generate_env() -> None:
    ENV_FILE.parent.mkdir(parents=True, exist_ok=True)
    if ENV_FILE.exists():
        print(f"[OK] Existing configuration preserved: {ENV_FILE}")
        return
    password = secrets.token_urlsafe(36)
    agent_token = secrets.token_urlsafe(48)
    setup_key = secrets.token_urlsafe(24)
    text = (
        "# Generated by scripts/install.py; keep this file private.\n"
        f"POSTGRES_PASSWORD={password}\n"
        f"AGENT_TOKEN={agent_token}\n"
        f"SETUP_KEY={setup_key}\n"
        "PANEL_BIND=127.0.0.1\n"
        "PANEL_PUBLIC_URL=http://localhost:3000\n"
        "NODE_ID=1\n"
    )
    descriptor = os.open(ENV_FILE, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(descriptor, "w", encoding="utf-8") as file:
        file.write(text)
    print(f"[OK] Generated secrets at {ENV_FILE} (permissions 0600).")
    print(f"[IMPORTANT] One-time admin setup key: {setup_key}")
    print("[IMPORTANT] Save it now, or read SETUP_KEY from deploy/.env later.")


def main() -> int:
    parser = argparse.ArgumentParser(description="Madar installer for Ubuntu 24.04 / 26.04")
    parser.add_argument("command", choices=["check", "env", "install", "status"], help="Run preflight, generate secrets, install or inspect services")
    parser.add_argument("--install-docker", action="store_true", help="Install Docker from its official signed Ubuntu repository if missing")
    parser.add_argument("--skip-os-check", action="store_true", help="Allow non-Ubuntu development hosts")
    args = parser.parse_args()
    try:
        check_host(skip_os_check=args.skip_os_check)
        if args.command == "env":
            generate_env()
            return 0
        if not docker_available() and args.install_docker:
            install_docker()
        if not docker_available():
            raise RuntimeError("Docker Compose is required. Re-run with --install-docker or see " + DOCKER_DOCS)
        print("[OK] Docker Compose detected.")
        if args.command == "check":
            return 0
        if args.command == "install":
            generate_env()
            run(["docker", "compose", "--env-file", str(ENV_FILE), "up", "-d", "--build", "--wait"])
            print("[OK] Madar is running at http://127.0.0.1:3000")
            print("Use an SSH tunnel or an HTTPS reverse proxy for remote access.")
        elif args.command == "status":
            if not ENV_FILE.exists():
                raise RuntimeError("No deploy/.env found. Run the install command first.")
            run(["docker", "compose", "--env-file", str(ENV_FILE), "ps"])
        return 0
    except (RuntimeError, OSError, subprocess.CalledProcessError) as error:
        print(f"[ERROR] {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
